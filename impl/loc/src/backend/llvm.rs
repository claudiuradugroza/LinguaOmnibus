//! LLVM IR backend for Lingua Omnibus.

use crate::backend::{Backend, BackendError};
use std::process::Command;
use std::fs;

pub struct LlvmBackend;

impl LlvmBackend {
    pub fn new() -> Self { Self }

    fn sanitize_ident(&self, name: &str) -> String {
        name.chars().map(|c| if c.is_alphanumeric() || c == '_' { c } else { '_' }).collect()
    }

    fn sanitize_reg(&self, r: &str) -> String {
        r.trim().trim_start_matches('%').to_string()
    }

    pub fn emit_ir(&self, lir_source: &str) -> Result<String, BackendError> {
        let mut ir = String::new();
        ir.push_str("; Generated by loc 0.1.0 - LLVM IR backend\n");
        ir.push_str("target triple = \"x86_64-pc-windows-msvc\"\n\n");
        ir.push_str("declare i32 @printf(i8*, ...)\n");
        ir.push_str("declare i32 @puts(i8*)\n");
        ir.push_str("declare void @exit(i32)\n");
        ir.push_str("@.fmt_int = private unnamed_addr constant [4 x i8] c\"%d\\0A\\00\"\n\n");

        // externs
        let mut externs: std::collections::HashSet<String> = std::collections::HashSet::new();
        for line in lir_source.lines() {
            let t = line.trim();
            if t.starts_with("extern fn ") {
                let rest = &t["extern ".len()..];
                if let Some(colon) = rest.find(" : ") {
                    externs.insert(rest[3..colon].trim().to_string());
                }
            }
        }

        // strings
        let mut strings: Vec<(String, String)> = Vec::new();
        let mut str_index: std::collections::HashMap<String, usize> = std::collections::HashMap::new();
        for line in lir_source.lines() {
            let t = line.trim();
            if t.contains("const.str") {
                if let (Some(s), Some(e)) = (t.find('"'), t.rfind('"')) {
                    if e > s {
                        let reg = if let Some(eq) = t.find('=') {
                            t[..eq].trim().trim_start_matches('%').to_string()
                        } else {
                            format!("str{}", strings.len())
                        };
                        str_index.insert(reg.clone(), strings.len());
                        strings.push((reg, t[s..=e].to_string()));
                    }
                }
            }
        }
        for (i, (_, s)) in strings.iter().enumerate() {
            let sz = s.len() - 1;
            let content = &s[1..s.len()-1];
            ir.push_str(&format!("@.str{} = private unnamed_addr constant [{} x i8] c\"{}\\00\"\n", i, sz, content));
        }
        if !strings.is_empty() { ir.push('\n'); }

        let lines: Vec<&str> = lir_source.lines().collect();
        let mut i = 0;
        while i < lines.len() {
            let trimmed = lines[i].trim();
            i += 1;
            if trimmed.is_empty() || trimmed.starts_with("lir ") || trimmed.starts_with("module") || trimmed == "}" {
                continue;
            }
            if trimmed.starts_with("extern fn ") {
                let rest = &trimmed["extern ".len()..];
                let name = if let Some(c) = rest.find(" : ") { rest[3..c].trim() } else { "f" };
                let san = self.sanitize_ident(name);
                let mut params_ir = Vec::new();
                if let (Some(ps), Some(pe)) = (rest.find('('), rest.find(')')) {
                    for p in rest[ps+1..pe].split(',') {
                        let p = p.trim();
                        if p.is_empty() { continue; }
                        let parts: Vec<&str> = p.split_whitespace().collect();
                        if parts.len() >= 2 {
                            params_ir.push(format!("{} %{}", self.lir_type_to_llvm(parts[0]), parts[1]));
                        }
                    }
                }
                let ret = if let Some(a) = rest.find("->") {
                    self.lir_type_to_llvm(rest[a+2..].trim())
                } else { "void".to_string() };
                ir.push_str(&format!("declare {} @{}({})\n", ret, san, params_ir.join(", ")));
                continue;
            }
            if trimmed.starts_with("fn ") {
                let name = if let Some(c) = trimmed.find(" : ") { trimmed[3..c].trim() } else { "main" };
                let san = self.sanitize_ident(name);
                let asm_name = if name == "main" { "main".to_string() } else { format!("lo_{}", san) };

                let mut params_ir = Vec::new();
                if let (Some(ps), Some(pe)) = (trimmed.find('('), trimmed.find(')')) {
                    for p in trimmed[ps+1..pe].split(',') {
                        let p = p.trim();
                        if p.is_empty() { continue; }
                        let parts: Vec<&str> = p.split_whitespace().collect();
                        if parts.len() >= 2 {
                            params_ir.push(format!("{} %{}", self.lir_type_to_llvm(parts[0]), parts[1]));
                        }
                    }
                }
                let ret = if let Some(a) = trimmed.find("->") {
                    self.lir_type_to_llvm(trimmed[a+2..].trim().trim_end_matches('{').trim())
                } else { "void".to_string() };

                ir.push_str(&format!("define {} @{}({}) {{\n", ret, asm_name, params_ir.join(", ")));
                ir.push_str("entry:\n");

                let mut block_terminated = false;
                while i < lines.len() {
                    let l = lines[i].trim();
                    i += 1;
                    if l.is_empty() { continue; }
                    if l == "}" {
                        if !block_terminated { ir.push_str("  unreachable\n"); }
                        break;
                    }
                    if l == "entry:" { continue; }
                    if l.ends_with(':') && !l.contains(' ') {
                        if !block_terminated {
                            ir.push_str("  unreachable\n");
                        }
                        block_terminated = false;
                        ir.push_str(&format!("{}\n", l));
                        continue;
                    }

                    if l.starts_with('%') && l.contains('=') {
                        let eq = l.find('=').unwrap();
                        let lhs = l[..eq].trim().trim_start_matches('%').to_string();
                        let rhs = l[eq+1..].trim();
                        let (op, rest) = if let Some(sp) = rhs.split_whitespace().next() {
                            (sp, rhs[sp.len()..].trim())
                        } else { ("", "") };
                        let llvm_lhs = format!("%{}", lhs);
                        match op {
                            "const.int" => {
                                ir.push_str(&format!("  {} = add i32 0, {}\n", llvm_lhs, rest.trim()));
                            }
                            "const.str" => {
                                if let Some(&idx) = str_index.get(&lhs) {
                                    let sz = strings[idx].1.len() - 1;
                                    ir.push_str(&format!("  {} = getelementptr inbounds [{} x i8], [{} x i8]* @.str{}, i64 0, i64 0\n", llvm_lhs, sz, sz, idx));
                                } else {
                                    ir.push_str(&format!("  {} = inttoptr i64 0 to i8*\n", llvm_lhs));
                                }
                            }
                            "add" => {
                                let parts: Vec<&str> = rest.split(',').collect();
                                let a = self.sanitize_reg(parts.get(0).unwrap_or(&"0"));
                                let b = self.sanitize_reg(parts.get(1).unwrap_or(&"0"));
                                ir.push_str(&format!("  {} = add i32 %{}, %{}\n", llvm_lhs, a, b));
                            }
                            "sub" => {
                                let parts: Vec<&str> = rest.split(',').collect();
                                let a = self.sanitize_reg(parts.get(0).unwrap_or(&"0"));
                                let b = self.sanitize_reg(parts.get(1).unwrap_or(&"0"));
                                ir.push_str(&format!("  {} = sub i32 %{}, %{}\n", llvm_lhs, a, b));
                            }
                            "mul" => {
                                let parts: Vec<&str> = rest.split(',').collect();
                                let a = self.sanitize_reg(parts.get(0).unwrap_or(&"0"));
                                let b = self.sanitize_reg(parts.get(1).unwrap_or(&"0"));
                                ir.push_str(&format!("  {} = mul i32 %{}, %{}\n", llvm_lhs, a, b));
                            }
                            "le" | "lt" | "ge" | "gt" | "eq" | "ne" => {
                                let parts: Vec<&str> = rest.split(',').collect();
                                let a = self.sanitize_reg(parts.get(0).unwrap_or(&"0"));
                                let b = self.sanitize_reg(parts.get(1).unwrap_or(&"0"));
                                let pred = match op {
                                    "le" => "sle", "lt" => "slt", "ge" => "sge",
                                    "gt" => "sgt", "eq" => "eq", "ne" => "ne", _ => "eq",
                                };
                                ir.push_str(&format!("  {} = icmp {} i32 %{}, %{}\n", llvm_lhs, pred, a, b));
                            }
                            "move" | "copy" => {
                                let src = self.sanitize_reg(rest);
                                ir.push_str(&format!("  {} = add i32 %{}, 0\n", llvm_lhs, src));
                            }
                            "call" => {
                                let full = rest;
                                if let Some(paren_start) = full.find('(') {
                                    let func_name = full[..paren_start].trim().trim_start_matches('%').trim_start_matches("call ").trim();
                                    let args_str = &full[paren_start..];
                                    let san_func = self.sanitize_ident(func_name);
                                    let args_inner = args_str.trim_start_matches('(').trim_end_matches(')');
                                    let sanitized_args = args_inner.split(',').map(|a| {
                                        let a = a.trim();
                                        format!("i32 {}", a)
                                    }).collect::<Vec<_>>().join(", ");
                                    if san_func == "print" && !args_inner.is_empty() {
                                        let arg_trimmed = args_inner.trim().trim_start_matches('(').trim_end_matches(')').trim().trim_start_matches('%');
                                        let is_str = str_index.contains_key(arg_trimmed);
                                        if is_str {
                                            ir.push_str(&format!("  {} = call i32 @puts(i8* %{})\n", llvm_lhs, arg_trimmed));
                                        } else {
                                            ir.push_str(&format!("  {} = call i32 (i8*, ...) @printf(i8* getelementptr inbounds ([4 x i8], [4 x i8]* @.fmt_int, i64 0, i64 0), i32 %{})\n", llvm_lhs, arg_trimmed));
                                        }
                                    } else {
                                        let call_func = if externs.contains(func_name) {
                                            san_func.clone()
                                        } else if san_func == "fib" {
                                            "lo_fib".to_string()
                                        } else if san_func == "main" {
                                            "main".to_string()
                                        } else {
                                            format!("lo_{}", san_func)
                                        };
                                        ir.push_str(&format!("  {} = call i32 @{}({})\n", llvm_lhs, call_func, sanitized_args));
                                    }
                                } else {
                                    ir.push_str(&format!("  {} = add i32 0, 0\n", llvm_lhs));
                                }
                            }
                            _ => {
                                ir.push_str(&format!("  ; unsupported op: {}\n", op));
                                ir.push_str(&format!("  {} = add i32 0, 0\n", llvm_lhs));
                            }
                        }
                    } else if l.starts_with("br.cond") {
                        let parts: Vec<&str> = l.split_whitespace().collect();
                        if parts.len() >= 4 {
                            let cond = self.sanitize_reg(parts[1].trim_end_matches(','));
                            let ltrue = parts[2].trim_end_matches(',');
                            let lfalse = parts[3];
                            ir.push_str(&format!("  br i1 %{}, label %{}, label %{}\n", cond, ltrue, lfalse));
                            block_terminated = true;
                        }
                    } else if l.starts_with("br ") {
                        let parts: Vec<&str> = l.split_whitespace().collect();
                        if parts.len() >= 2 {
                            ir.push_str(&format!("  br label %{}\n", parts[1]));
                            block_terminated = true;
                        }
                    } else if l.starts_with("asm") {
                        let code = l["asm".len()..].trim().trim_matches('"');
                        ir.push_str(&format!("  call void asm sideeffect \"{}\", \"\"()\n", code));
                    } else if l.starts_with("store") {
                        // store is not fully lowered in LLVM IR yet (placeholder)
                        ir.push_str("  ; store (placeholder)\n");
                    } else if l.starts_with("ret") {
                        let val = l["ret ".len()..].trim();
                        if val == "unit" || val.is_empty() {
                            ir.push_str("  ret void\n");
                        } else {
                            let v = self.sanitize_reg(val);
                            ir.push_str(&format!("  ret i32 %{}\n", v));
                        }
                        block_terminated = true;
                    } else if l == "}" {
                        // handled by outer break
                    } else {
                        ir.push_str(&format!("  ; {}\n", l));
                    }
                }

                ir.push_str("}\n\n");
                continue;
            }
        }

        Ok(ir)
    }

    fn lir_type_to_llvm(&self, t: &str) -> String {
        match t.trim() {
            "i32" | "int32" => "i32".to_string(),
            "i64" | "int64" => "i64".to_string(),
            "f32" => "float".to_string(),
            "f64" | "double" => "double".to_string(),
            "v4f32" => "<4 x float>".to_string(),
            "v8f32" => "<8 x float>".to_string(),
            "v2f64" => "<2 x double>".to_string(),
            "v4i32" => "<4 x i32>".to_string(),
            "v8i32" => "<8 x i32>".to_string(),
            "v2i64" => "<2 x i64>".to_string(),
            "bool" => "i1".to_string(),
            "unit" => "void".to_string(),
            "string" | "str" => "i8*".to_string(),
            _ => "i32".to_string(),
        }
    }
}

impl Backend for LlvmBackend {
    fn name(&self) -> &'static str { "llvm" }
    fn emit(&self, lir_source: &str) -> Result<Vec<u8>, BackendError> {
        let ir = self.emit_ir(lir_source)?;
        let tmp = std::env::temp_dir();
        let ll_path = tmp.join("loc-out.ll");
        let bin_path = tmp.join("loc-out-llvm");
        std::fs::write(&ll_path, &ir).map_err(BackendError::IoError)?;
        let mut compiled = false;
        for compiler in ["clang", "C:\\Program Files\\LLVM\\bin\\clang.exe"] {
            let result = Command::new(compiler)
                .args(["-x", "ir", ll_path.to_str().unwrap(), "-o", bin_path.to_str().unwrap(), "-O2"])
                .status();
            match result {
                Ok(s) if s.success() => { compiled = true; break; }
                _ => continue,
            }
        }
        if !compiled {
            return Err(BackendError::LinkerError("no compiler found for LLVM IR".into()));
        }
        std::fs::read(&bin_path).map_err(BackendError::IoError)
    }
}
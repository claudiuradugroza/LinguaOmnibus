//! Native x86_64 backend for Lingua Omnibus.
//!
//! Generates x86_64 assembly directly from LIR (no C intermediate).
//! Uses Intel syntax, assembled with clang/gcc.

use crate::backend::{Backend, BackendError};
use std::collections::HashMap;
use std::process::Command;
use std::fs;

pub struct X86_64Backend;

impl X86_64Backend {
    pub fn new() -> Self {
        Self
    }

    /// Emit x86_64 assembly from LIR text.
    fn emit_asm(&self, lir_source: &str) -> String {
        let mut asm = String::new();
        asm.push_str("# Generated by loc 0.1.0 - x86_64 native backend\n");
        asm.push_str(".intel_syntax noprefix\n");
        asm.push_str(".section .text\n");
        asm.push_str(".globl main\n");

        let mut strings: Vec<(String, String)> = Vec::new();
        let mut string_regs: std::collections::HashSet<String> = std::collections::HashSet::new();
        let mut string_counter = 0;

        // Parse LIR
        let lines: Vec<&str> = lir_source.lines().collect();
        let mut i = 0;

        while i < lines.len() {
            let trimmed = lines[i].trim();
            i += 1;

            if trimmed.is_empty() || trimmed.starts_with("lir ") || trimmed.starts_with("module") || trimmed == "}" {
                continue;
            }

            if trimmed.starts_with("fn ") {
                let name = if let Some(colon_pos) = trimmed.find(" : ") {
                    trimmed[3..colon_pos].trim()
                } else {
                    "main"
                };
                let sanitized = self.sanitize(name);
                // Prefix with lo_ for non-main functions
                let asm_name = if name == "main" { "main".to_string() } else { format!("lo_{}", sanitized) };

                let params = if let Some(paren_start) = trimmed.find('(') {
                    if let Some(paren_end) = trimmed.find(')') {
                        trimmed[paren_start + 1..paren_end].trim()
                    } else {
                        ""
                    }
                } else {
                    ""
                };

                let sanitized = self.sanitize(name);
                asm.push_str(&format!("\n{}:\n", asm_name));
                asm.push_str("    push rbp\n");
                asm.push_str("    mov rbp, rsp\n");
                asm.push_str("    sub rsp, 256\n");

                let mut reg_map: HashMap<String, i32> = HashMap::new();
                let mut next_slot: i32 = -8;

                // Map parameters to stack slots
                if !params.is_empty() {
                    let param_list: Vec<&str> = params.split(',').collect();
                    if param_list.len() >= 1 {
                        let p = param_list[0].trim();
                        let parts: Vec<&str> = p.split_whitespace().collect();
                        if parts.len() >= 2 {
                            let pname = parts[1];
                            let slot = self.reg_slot(pname, &mut reg_map, &mut next_slot);
                            asm.push_str(&format!("    mov [rbp + {}], rcx\n", slot));
                        }
                    }
                }

                // Process instructions until closing brace
                while i < lines.len() {
                    let instr = lines[i].trim();
                    i += 1;

                    if instr == "}" || instr.is_empty() {
                        break;
                    }

                    if instr == "entry:" {
                        continue;
                    }

                    if instr.ends_with(':') && !instr.contains('=') && !instr.starts_with('%') {
                        let label = instr.trim_end_matches(':');
                        asm.push_str(&format!("{}:\n", label));
                        continue;
                    }

                    if instr.starts_with("ret ") {
                        let parts: Vec<&str> = instr.split_whitespace().collect();
                        if parts.len() >= 2 && parts[1] == "unit" {
                            asm.push_str("    xor eax, eax\n");
                            asm.push_str("    mov rsp, rbp\n");
                            asm.push_str("    pop rbp\n");
                            asm.push_str("    ret\n");
                        } else if parts.len() >= 2 {
                            let reg = parts[1].trim_start_matches('%');
                            if let Some(&slot) = reg_map.get(reg) {
                                asm.push_str(&format!("    mov rax, [rbp + {}]\n", slot));
                            } else {
                                asm.push_str(&format!("    mov rax, {}\n", reg));
                            }
                            asm.push_str("    mov rsp, rbp\n");
                            asm.push_str("    pop rbp\n");
                            asm.push_str("    ret\n");
                        }
                        continue;
                    }

                    if instr.starts_with("br.cond") {
                        let parts: Vec<&str> = instr.split_whitespace().collect();
                        if parts.len() >= 4 {
                            let cond_reg = parts[1].trim_start_matches('%').trim_end_matches(',');
                            let t_label = parts[2].trim_end_matches(',');
                            let f_label = parts[3];
                            let cond_slot = reg_map.get(cond_reg).copied().unwrap_or(-8);
                            asm.push_str(&format!("    mov rax, [rbp + {}]\n", cond_slot));
                            asm.push_str("    cmp rax, 0\n");
                            asm.push_str(&format!("    je {}\n", f_label));
                            asm.push_str(&format!("    jmp {}\n", t_label));
                        }
                        continue;
                    }

                    if instr.starts_with("br ") {
                        let parts: Vec<&str> = instr.split_whitespace().collect();
                        if parts.len() >= 2 {
                            asm.push_str(&format!("    jmp {}\n", parts[1]));
                        }
                        continue;
                    }

                    if instr.contains(" = ") {
                        let eq_parts: Vec<&str> = instr.splitn(2, " = ").collect();
                        if eq_parts.len() == 2 {
                            let lhs = eq_parts[0].trim().trim_start_matches('%');
                            let rhs = eq_parts[1].trim();
                            let rhs_parts: Vec<&str> = rhs.split_whitespace().collect();

                            if rhs_parts.is_empty() {
                                continue;
                            }

                            let lhs_slot = self.reg_slot(lhs, &mut reg_map, &mut next_slot);

                            match rhs_parts[0] {
                                "const.int" => {
                                    if rhs_parts.len() >= 2 {
                                        asm.push_str(&format!("    mov qword ptr [rbp + {}], {}\n", lhs_slot, rhs_parts[1]));
                                    }
                                }
                                "const.str" => {
                                    let str_val = if rhs.contains('"') {
                                        let start = rhs.find('"').unwrap_or(0);
                                        let end = rhs.rfind('"').unwrap_or(rhs.len());
                                        &rhs[start..=end]
                                    } else {
                                        "\"\""
                                    };
                                    let label = format!(".Lstr_{}", lhs);
                                    strings.push((label.clone(), str_val.to_string()));
                                    string_regs.insert(lhs.to_string());
                                    asm.push_str(&format!("    lea rax, [rip + {}]\n", label));
                                    asm.push_str(&format!("    mov [rbp + {}], rax\n", lhs_slot));
                                }
                                "const.unit" => {
                                    asm.push_str(&format!("    mov qword ptr [rbp + {}], 0\n", lhs_slot));
                                }
                                "add" => {
                                    if rhs_parts.len() >= 3 {
                                        let a = rhs_parts[1].trim_end_matches(',');
                                        let b = rhs_parts[2];
                                        let a_slot = reg_map.get(a.trim_start_matches('%')).copied().unwrap_or(0);
                                        let b_slot = reg_map.get(b.trim_start_matches('%')).copied().unwrap_or(0);
                                        asm.push_str(&format!("    mov rax, [rbp + {}]\n", a_slot));
                                        asm.push_str(&format!("    add rax, [rbp + {}]\n", b_slot));
                                        asm.push_str(&format!("    mov [rbp + {}], rax\n", lhs_slot));
                                    }
                                }
                                "sub" => {
                                    if rhs_parts.len() >= 3 {
                                        let a = rhs_parts[1].trim_end_matches(',');
                                        let b = rhs_parts[2];
                                        let a_slot = reg_map.get(a.trim_start_matches('%')).copied().unwrap_or(0);
                                        let b_slot = reg_map.get(b.trim_start_matches('%')).copied().unwrap_or(0);
                                        asm.push_str(&format!("    mov rax, [rbp + {}]\n", a_slot));
                                        asm.push_str(&format!("    sub rax, [rbp + {}]\n", b_slot));
                                        asm.push_str(&format!("    mov [rbp + {}], rax\n", lhs_slot));
                                    }
                                }
                                "mul" => {
                                    if rhs_parts.len() >= 3 {
                                        let a = rhs_parts[1].trim_end_matches(',');
                                        let b = rhs_parts[2];
                                        let a_slot = reg_map.get(a.trim_start_matches('%')).copied().unwrap_or(0);
                                        let b_slot = reg_map.get(b.trim_start_matches('%')).copied().unwrap_or(0);
                                        asm.push_str(&format!("    mov rax, [rbp + {}]\n", a_slot));
                                        asm.push_str(&format!("    imul rax, [rbp + {}]\n", b_slot));
                                        asm.push_str(&format!("    mov [rbp + {}], rax\n", lhs_slot));
                                    }
                                }
                                "le" => {
                                    if rhs_parts.len() >= 3 {
                                        let a = rhs_parts[1].trim_end_matches(',');
                                        let b = rhs_parts[2];
                                        let a_slot = reg_map.get(a.trim_start_matches('%')).copied().unwrap_or(0);
                                        let b_slot = reg_map.get(b.trim_start_matches('%')).copied().unwrap_or(0);
                                        asm.push_str(&format!("    mov rax, [rbp + {}]\n", a_slot));
                                        asm.push_str(&format!("    cmp rax, [rbp + {}]\n", b_slot));
                                        asm.push_str("    setle al\n");
                                        asm.push_str("    movzx rax, al\n");
                                        asm.push_str(&format!("    mov [rbp + {}], rax\n", lhs_slot));
                                    }
                                }
                                "move" | "copy" => {
                                    if rhs_parts.len() >= 2 {
                                        let src = rhs_parts[1].trim_start_matches('%');
                                        let src_slot = reg_map.get(src).copied().unwrap_or(0);
                                        asm.push_str(&format!("    mov rax, [rbp + {}]\n", src_slot));
                                        asm.push_str(&format!("    mov [rbp + {}], rax\n", lhs_slot));
                                    }
                                }
                                "call" => {
                                    let call_str = rhs.trim_start_matches("call ").trim();
                                    if let Some(paren_start) = call_str.find('(') {
                                        let func_name = &call_str[..paren_start];
                                        let func_sanitized = func_name.trim_start_matches('%');
                                        let args_str = &call_str[paren_start..];
                                        let args_inner = args_str.trim_start_matches('(').trim_end_matches(')');

                                        if func_sanitized == "print" {
                                            let arg = args_inner.replace('%', "");
                                            let is_str = string_regs.contains(&arg);
                                            if is_str {
                                                asm.push_str("    lea rcx, [rip + .Lfmt_str]\n");
                                            } else {
                                                asm.push_str("    lea rcx, [rip + .Lfmt_int]\n");
                                            }
                                            if let Some(&slot) = reg_map.get(&arg) {
                                                asm.push_str(&format!("    mov rdx, [rbp + {}]\n", slot));
                                            } else {
                                                asm.push_str(&format!("    mov rdx, {}\n", arg));
                                            }
                                            asm.push_str("    xor eax, eax\n");
                                            asm.push_str("    call printf\n");
                                            asm.push_str(&format!("    mov [rbp + {}], rax\n", lhs_slot));
                                        } else if func_sanitized == "alloc_qubit" {
                                            asm.push_str("    call lo_alloc_qubit\n");
                                            asm.push_str(&format!("    mov [rbp + {}], rax\n", lhs_slot));
                                        } else if func_sanitized == "measure" || func_sanitized == "KW_MEASURE" {
                                            let arg = args_inner.replace('%', "");
                                            if let Some(&slot) = reg_map.get(&arg) {
                                                asm.push_str(&format!("    mov rdi, [rbp + {}]\n", slot));
                                            }
                                            asm.push_str("    call lo_measure\n");
                                            asm.push_str(&format!("    mov [rbp + {}], rax\n", lhs_slot));
                                        } else {
                                            let c_func = format!("lo_{}", func_sanitized);
                                            if !args_inner.is_empty() {
                                                let arg = args_inner.split(',').next().unwrap_or("").trim().replace('%', "");
                                                if let Some(&slot) = reg_map.get(&arg) {
                                                    asm.push_str(&format!("    mov rcx, [rbp + {}]\n", slot));
                                                } else {
                                                    asm.push_str(&format!("    mov rcx, {}\n", arg));
                                                }
                                            }
                                            asm.push_str(&format!("    call {}\n", c_func));
                                            asm.push_str(&format!("    mov [rbp + {}], rax\n", lhs_slot));
                                        }
                                    }
                                }
                                _ => {}
                            }
                        }
                    }
                }
            }
        }

        // Add .rodata section for strings
        asm.push_str("\n.section .rodata\n");
        asm.push_str(".Lfmt_str:\n");
        asm.push_str("    .asciz \"%s\\n\"\n");
        asm.push_str(".Lfmt_int:\n");
        asm.push_str("    .asciz \"%lld\\n\"\n");
        for (label, val) in &strings {
            asm.push_str(&format!("{}:\n", label));
            asm.push_str(&format!("    .asciz {}\n", val));
        }

        asm
    }

    fn reg_slot(&self, reg: &str, reg_map: &mut HashMap<String, i32>, next_slot: &mut i32) -> i32 {
        let reg = reg.trim().trim_start_matches('%').trim_end_matches(',');
        if let Some(&slot) = reg_map.get(reg) {
            return slot;
        }
        let slot = *next_slot;
        *next_slot -= 8;
        reg_map.insert(reg.to_string(), slot);
        slot
    }

    fn sanitize(&self, name: &str) -> String {
        name.chars()
            .map(|c| if c.is_alphanumeric() || c == '_' { c } else { '_' })
            .collect()
    }
}

impl Backend for X86_64Backend {
    fn name(&self) -> &'static str {
        "x86_64"
    }

    fn emit(&self, lir_source: &str) -> Result<Vec<u8>, BackendError> {
        let asm_source = self.emit_asm(lir_source);

        let temp_dir = std::env::temp_dir();
        let temp_asm = temp_dir.join("loc-gen.s");
        let temp_bin = temp_dir.join("loc-gen");

        fs::write(&temp_asm, &asm_source)
            .map_err(|e| BackendError::IoError(e))?;

        let clang_path = "C:\\Program Files\\LLVM\\bin\\clang.exe";
        let status = Command::new(clang_path)
            .args(&["-Wl,/SUBSYSTEM:CONSOLE", "-o", temp_bin.to_str().unwrap(), temp_asm.to_str().unwrap()])
            .status()
            .map_err(|e| BackendError::IoError(e))?;

        if !status.success() {
            return Err(BackendError::LinkerError(format!(
                "clang failed; ASM source at {}", temp_asm.display()
            )));
        }

        fs::read(&temp_bin).map_err(|e| BackendError::IoError(e))
    }
}

#[cfg(test)]
mod tests {
    use super::*;

    #[test]
    fn test_sanitize() {
        let backend = X86_64Backend::new();
        assert_eq!(backend.sanitize("hello"), "hello");
        assert_eq!(backend.sanitize("foo_bar"), "foo_bar");
    }

    #[test]
    fn test_emit_asm_header() {
        let backend = X86_64Backend::new();
        let asm = backend.emit_asm("lir 1.2.0\nmodule main {\n}\n");
        assert!(asm.contains("Generated by loc"));
        assert!(asm.contains(".intel_syntax noprefix"));
    }
}